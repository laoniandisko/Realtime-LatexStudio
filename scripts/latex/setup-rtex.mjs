import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { runCommand } from './process.mjs';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const version = '0.0.6';
if (process.platform !== 'win32' || process.arch !== 'x64') throw Error('This setup helper targets Windows x64. See https://github.com/HenryXiaoYang/realtime-tex/releases for other platforms.');
const name = 'rtex-x86_64-pc-windows-msvc.zip';
const url = `https://github.com/HenryXiaoYang/realtime-tex/releases/download/v${version}/${name}`;
const runtime = path.join(root, '.runtime/rtex'); await fs.mkdir(runtime, { recursive: true });
const [archive, checksum] = await Promise.all([fetch(url, { signal: AbortSignal.timeout(120000) }).then(r => { if (!r.ok) throw Error(r.status); return r.arrayBuffer(); }), fetch(url + '.sha256', { signal: AbortSignal.timeout(30000) }).then(r => { if (!r.ok) throw Error(r.status); return r.text(); })]);
const data = Buffer.from(archive), hash = createHash('sha256').update(data).digest('hex');
if (!checksum.includes(hash)) throw Error('Release SHA-256 verification failed.');
await fs.writeFile(path.join(runtime, 'windows.zip'), data);
const command = "$ErrorActionPreference='Stop'; Expand-Archive -LiteralPath " + "'" + path.join(runtime, 'windows.zip').replaceAll("'", "''") + "' -DestinationPath '" + path.join(runtime, 'bin').replaceAll("'", "''") + "' -Force";
const extracted = await runCommand('powershell.exe', ['-NoLogo', '-NoProfile', '-NonInteractive', '-EncodedCommand', Buffer.from(command, 'utf16le').toString('base64')], { timeoutMs: 60000 });
if (extracted.code !== 0) throw Error(extracted.stderr || 'Release extraction failed.');
console.log(`Installed realtime-tex ${version}; verified SHA-256 ${hash}.`);
console.log('A LuaLaTeX installation is also required. Set SIDEX_TEXLIVE_BIN for an existing TeX Live bin directory.');
